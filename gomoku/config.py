"""全局配置层。

设计原则：所有可调参数集中于此，便于统一修改与调优，
避免"魔法数字"散落在业务代码中（符合工程化与可维护性要求）。
"""
from __future__ import annotations

# ---------------------------------------------------------------------------
# 棋盘与规则
# ---------------------------------------------------------------------------
BOARD_SIZE = 15          # 标准五子棋棋盘边长（15 x 15）
WIN_COUNT = 5            # 连成多少子即获胜（freestyle 自由规则：>= WIN_COUNT 即胜）
CANDIDATE_RADIUS = 2     # 启发式候选点搜索半径：仅考虑已有棋子周围该范围内的空点

# ---------------------------------------------------------------------------
# 棋型评分表（数值越大代表棋型越关键 / 越接近获胜）
# 采用"先数连子数，再看两端开放情况"的刻画方式。
# ---------------------------------------------------------------------------
SCORE_FIVE = 10_000_000      # 成五（必胜）
SCORE_OPEN_FOUR = 1_000_000  # 活四：两端皆空，对方无法同时封堵，下一手必成五
SCORE_FOUR = 100_000         # 冲四：仅一端可成五（另一端被挡），下一步可成五，必须封堵
SCORE_OPEN_THREE = 10_000    # 活三：两端皆空，下一步可成活四
SCORE_THREE = 1_000          # 眠三：仅一端开放，需警惕
SCORE_OPEN_TWO = 1_000       # 活二：两端皆空
SCORE_TWO = 100              # 眠二
SCORE_ONE = 10               # 单子

# 防守权重：综合评分 = 进攻分 + 防守分 * DEFENSE_WEIGHT
# 设为 1.0 表示进攻与防守同等重要；调大则更偏向防守。
DEFENSE_WEIGHT = 1.0

# 自对弈 / LLM 调用相关默认参数
LLM_TIMEOUT = 60             # LLM 接口单次请求超时（秒，推理模型较慢需留足）
LLM_TEMPERATURE = 0.2        # 低温度，保证落子决策稳定、可复现
LLM_MAX_RETRIES = 3          # LLM 返回非法落子时的最大重试次数

# 搜索型棋手（negamax + α-β）默认参数
SEARCH_DEPTH = 4             # 搜索深度（向前看几步）
SEARCH_TOP_K = 12            # 每节点仅保留评分最高的前 K 个候选，控制分支宽度
